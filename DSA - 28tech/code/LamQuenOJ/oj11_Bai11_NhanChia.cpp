#include <bits/stdc++.h>
#define ll long long
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(NULL);
    int n;
    cin >> n;
    cout << (ll) n * 2 << endl;
    cout << (ll) n * 10 << endl;
    cout << n / 2 << endl;
    cout << fixed << setprecision(3) << (double) n / 2 << endl;

    return 0;
}
